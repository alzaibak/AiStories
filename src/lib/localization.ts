const catalog: Record<Exclude<SiteLanguage, 'ar'>, Record<string, string>> = { en: english, fr: french };

export function translateText(value: string, language: SiteLanguage) {
  const translation = language === 'ar' ? arabic[value.trim()] : catalog[language][value.trim()];
  if (!translation) return value;
  const leading = value.match(/^\s*/)?.[0] || '';
  const trailing = value.match(/\s*$/)?.[0] || '';
  return `${leading}${translation}${trailing}`;
}

export function translateTree(node: ReactNode, language: SiteLanguage): ReactNode {
  if (typeof node === 'string') return translateText(node, language);
  if (Array.isArray(node)) return node.map((child) => translateTree(child, language));
  if (!isValidElement<{ children?: ReactNode }>(node)) return node;

  const props: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node.props)) {
    if (typeof value === 'string' && key !== 'to' && key !== 'className' && key !== 'value') {
      props[key] = translateText(value, language);
    } else if (key === 'children') {
      props.children = Children.map(value as ReactNode, (child) => translateTree(child, language));
    }
  }
  return cloneElement(node, props);
}
